"""systemd user units for hark on Linux, and the daemon's sd_notify(3) readiness/watchdog.

Units (``hark service install`` writes them; ``packaging/systemd/`` holds the packaged copies,
rendered by :func:`render` with :data:`PACKAGED` and pinned by a test):

- ``hark.service``: ``hark run``. ``Type=notify``: ready once the control socket answers; the
  watchdog is fed only while ``hark ctl ping`` gets an answer, so a wedged daemon is restarted.
  Part of ``graphical-session.target`` (uwsm, which Omarchy uses, starts that target after it
  exported ``WAYLAND_DISPLAY`` and ``HYPRLAND_INSTANCE_SIGNATURE`` to the user manager).
- ``hark-server.service``: ``skriv-server --config ~/.config/hark/server.toml``; ready once the
  model is warm (health SERVING); watchdog fed by its event loop. ``default.target``: with
  ``loginctl enable-linger`` it runs from boot, without a login.
- ``hark-llama.service``: ``scripts/llama-up`` (llama-server for cleanup on 127.0.0.1:8080);
  ready once ``/health`` answers 200.

Stdlib only: :func:`notify` and :func:`start_watchdog` run inside ``hark run``.
"""

from __future__ import annotations

import getpass
import logging
import os
import re
import subprocess
import sys
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

from skriv_client.service import COMPONENTS, InstallOptions, ServiceError, Status

if TYPE_CHECKING:
    from collections.abc import Callable, Mapping, Sequence

log = logging.getLogger("hark.service")

UNITS = {"client": "hark.service", "server": "hark-server.service", "llama": "hark-llama.service"}
MARKER = "# Generated by `hark service install`"
PACKAGED_VENV = Path("/usr/lib/hark/venv")  # where the hark-git package installs hark's venv
VENDOR_UNIT_DIR = Path("/usr/lib/systemd/user")  # the package's units
# What a compositor session must hand to the user manager for paste, focus and notifications.
SESSION_ENV = (
    "WAYLAND_DISPLAY",
    "DISPLAY",
    "HYPRLAND_INSTANCE_SIGNATURE",
    "XDG_CURRENT_DESKTOP",
    "XDG_SESSION_TYPE",
)
LLAMA_HEALTH = "http://127.0.0.1:8080/health"  # scripts/llama-up's address


@dataclass(frozen=True)
class Commands:
    """Absolute argv prefixes the units run; None where that program is not installed."""

    skriv: tuple[str, ...]
    server: tuple[str, ...] | None
    llama_up: tuple[str, ...] | None


PACKAGED = Commands(
    skriv=("/usr/bin/skriv",),
    server=("/usr/bin/skriv-server",),
    llama_up=("/usr/lib/hark/scripts/llama-up",),
)


def current_commands() -> Commands:
    """The programs of *this* installation: the venv running hark (uv tool, repo .venv) and,
    for an editable install, the checkout's ``scripts/llama-up``."""
    bindir = Path(sys.executable).parent  # not resolved: the venv's bin, not the base Python's
    skriv, server = bindir / "skriv", bindir / "skriv-server"
    llama_up = Path(__file__).resolve().parents[4] / "scripts" / "llama-up"
    return Commands(
        skriv=(str(skriv),) if skriv.is_file() else (sys.executable, "-m", "skriv_client"),
        server=(str(server),) if server.is_file() else None,
        llama_up=(str(llama_up),) if llama_up.is_file() else None,
    )


def is_packaged() -> bool:
    return Path(sys.prefix) == PACKAGED_VENV


def quote(arg: str) -> str:
    """One systemd command-line word: specifiers (%) and variables ($) taken literally."""
    escaped = arg.replace("%", "%%").replace("$", "$$")
    if re.fullmatch(r"[A-Za-z0-9_@%+=:,./$-]+", escaped):
        return escaped
    return '"' + escaped.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _exec(argv: Sequence[str]) -> str:
    return " ".join(quote(a) for a in argv)


def render(component: str, cmds: Commands) -> str:
    """The unit file for ``component`` running ``cmds``."""
    head = (
        f"{MARKER} (skriv_client/service/linux.py). Customise with a drop-in\n"
        "# (`systemctl --user edit <unit>`): edits here are lost on reinstall.\n"
    )
    if component == "client":
        return head + _CLIENT.format(exec=_exec([*cmds.skriv, "run"]))
    if component == "server":
        if cmds.server is None:
            raise ServiceError("skriv-server is not installed next to hark (uv sync in the repo)")
        return head + _SERVER.format(exec=_exec(cmds.server))
    if component == "llama":
        if cmds.llama_up is None:
            raise ServiceError(
                "scripts/llama-up not found: install from a hark checkout or the hark-git package"
            )
        return head + _LLAMA.format(exec=_exec(cmds.llama_up), health=LLAMA_HEALTH)
    raise ServiceError(f"unknown component {component!r}")


_CLIENT = """\
[Unit]
Description=hark dictation daemon
PartOf=graphical-session.target
After=graphical-session.target pipewire.service

[Service]
Type=notify
NotifyAccess=main
# Without a display in the user manager's environment hark could not paste: skip the start
# (not a failure). Import it and start again: see `hark service install` or docs/linux.md.
ExecCondition=/bin/sh -c 'test -n "$${{WAYLAND_DISPLAY}}$${{DISPLAY}}"'
ExecStart={exec}
Restart=on-failure
RestartSec=2
# exit 2 = configuration error: a restart cannot fix it
RestartPreventExitStatus=2
WatchdogSec=30
UMask=0077
NoNewPrivileges=yes

[Install]
WantedBy=graphical-session.target
"""

_SERVER = """\
[Unit]
Description=hark inference server (ASR + text cleanup proxy)
After=hark-llama.service

[Service]
Type=notify
NotifyAccess=main
ExecStart={exec} --config %E/hark/server.toml
Restart=on-failure
RestartSec=5
RestartSteps=5
RestartMaxDelaySec=2min
# exit 2 = configuration error, 3 = backend unavailable: a restart cannot fix them
RestartPreventExitStatus=2 3
# the first start may download the ASR model before health says SERVING
TimeoutStartSec=15min
WatchdogSec=30
UMask=0077
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"""

_LLAMA = """\
[Unit]
Description=llama-server for hark text cleanup (127.0.0.1:8080)
Before=hark-server.service

[Service]
Type=exec
ExecStart={exec}
# ready once the model is loaded (/health answers 503 until then)
ExecStartPost=curl -fsS -o /dev/null --retry 150 --retry-delay 1 --retry-connrefused {health}
TimeoutStartSec=3min
Restart=on-failure
RestartSec=5
UMask=0077
NoNewPrivileges=yes

[Install]
WantedBy=default.target
"""


def _out(line: str) -> None:
    print(line)


def _err(line: str) -> None:
    print(line, file=sys.stderr)


type Runner = Callable[[Sequence[str]], subprocess.CompletedProcess[str]]


def _run(argv: Sequence[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(argv, capture_output=True, text=True, check=False)  # noqa: S603


class SystemdBackend:
    components: tuple[str, ...] = COMPONENTS
    install_default: tuple[str, ...] = ("client",)

    def __init__(
        self,
        *,
        run: Runner = _run,
        env: Mapping[str, str] | None = None,
        commands: Commands | None = None,
        packaged: bool | None = None,
        vendor_dir: Path = VENDOR_UNIT_DIR,
    ) -> None:
        self.env = os.environ if env is None else env
        self.run = run
        self.packaged = is_packaged() if packaged is None else packaged
        self.commands = commands or (PACKAGED if self.packaged else current_commands())
        self.vendor_dir = vendor_dir
        config = self.env.get("XDG_CONFIG_HOME") or str(Path(self.env.get("HOME", "~")) / ".config")
        self.config_home = Path(config).expanduser()
        self.unit_dir = self.config_home / "systemd" / "user"

    def _systemctl(self, *args: str) -> subprocess.CompletedProcess[str]:
        try:
            return self.run(["systemctl", "--user", *args])
        except FileNotFoundError as e:
            raise ServiceError("systemctl not found: hark service needs systemd") from e

    def _check(self, *args: str) -> None:
        p = self._systemctl(*args)
        if p.returncode != 0:
            raise ServiceError(f"systemctl --user {' '.join(args)}: {p.stderr.strip()}")

    def _plan(self, components: Sequence[str], *, force: bool) -> list[tuple[str, str | None]]:
        """(unit, text to write or None = the package's unit) per component."""
        plan: list[tuple[str, str | None]] = []
        for c in components:
            unit = UNITS[c]
            if self.packaged:
                if not (self.vendor_dir / unit).is_file():
                    raise ServiceError(f"{self.vendor_dir / unit} missing: reinstall hark-git")
                plan.append((unit, None))
                continue
            path = self.unit_dir / unit
            if path.is_file() and MARKER not in path.read_text() and not force:
                raise ServiceError(f"{path} was not written by hark; keep it, or use --force")
            plan.append((unit, render(c, self.commands)))
        return plan

    def install(self, components: Sequence[str], opts: InstallOptions) -> int:
        if opts.asr_backend or opts.cleanup_model:
            _err(
                "hark service: --backend and --cleanup-model are for the macOS agents; on Linux"
                " hark-server.service reads ~/.config/hark/server.toml"
            )
            return 2
        start, dry_run = opts.start, opts.dry_run
        try:
            plan = self._plan(components, force=opts.force)
            imported = self._session_env() if "client" in components else []
            units = [u for u, _ in plan]
            steps = [
                *([["import-environment", *imported]] if imported else []),
                ["daemon-reload"],
                ["enable", *(["--now"] if start else []), *units],
            ]
            if dry_run:
                for unit, text in plan:
                    where = self.unit_dir / unit if text else self.vendor_dir / unit
                    _out(f"# {where}{'' if text else ' (installed by the package)'}")
                    if text:
                        _out(text)
                for step in steps:
                    _out(" ".join(["systemctl", "--user", *step]))
                return 0
            for unit, text in plan:
                if text is not None:
                    self._write(self.unit_dir / unit, text)
            for step in steps:
                self._check(*step)
        except ServiceError as e:
            _err(f"hark service: {e}")
            return 1
        _out(f"{'started' if start else 'enabled'}: {', '.join(units)}")
        self._hints(components, imported)
        return 0

    def _write(self, path: Path, text: str) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f".{path.name}.tmp")
        tmp.write_text(text)
        tmp.chmod(0o644)
        tmp.replace(path)
        _out(f"wrote {path}")

    def _session_env(self) -> list[str]:
        """Display variables of this shell to hand to the user manager (none: not in a session)."""
        if not (self.env.get("WAYLAND_DISPLAY") or self.env.get("DISPLAY")):
            _err(
                "hark service: no WAYLAND_DISPLAY/DISPLAY here; hark.service starts once the"
                " session exports them (run this from a terminal in your desktop session)"
            )
            return []
        return [name for name in SESSION_ENV if self.env.get(name)]

    def _hints(self, components: Sequence[str], imported: Sequence[str]) -> None:
        if "client" in components:
            session = self._systemctl("is-active", "graphical-session.target").stdout.strip()
            if session != "active":
                names = " ".join(n for n in imported if n != "DISPLAY") or "WAYLAND_DISPLAY"
                _out(
                    "note: graphical-session.target is not active (a compositor without uwsm),"
                    " so hark.service will not start at login by itself. In hyprland.conf:\n"
                    f"  exec-once = systemctl --user import-environment {names}"
                    " && systemctl --user start hark.service"
                )
        if "server" in components and not (self.config_home / "hark" / "server.toml").is_file():
            _out(
                f"note: hark-server.service reads {self.config_home / 'hark' / 'server.toml'},"
                " which does not exist yet (see docs/linux.md)"
            )
        if {"server", "llama"} & set(components):
            try:
                user = self.env.get("USER") or getpass.getuser()
                linger = self.run(["loginctl", "show-user", user, "--property=Linger", "--value"])
            except (OSError, KeyError):  # no loginctl / no user name
                return
            if linger.stdout.strip() == "no":
                _out(
                    "note: without a login the server stops; to keep it running from boot:"
                    " loginctl enable-linger"
                )

    def uninstall(self, components: Sequence[str]) -> int:
        units = [UNITS[c] for c in components]
        try:
            self._systemctl("disable", "--now", *units)  # fails for units never installed: fine
            for unit in units:
                path = self.unit_dir / unit
                if path.is_file() and MARKER in path.read_text():
                    path.unlink()
                    _out(f"removed {path}")
                elif path.is_file():
                    _out(f"kept {path} (not written by hark)")
            self._check("daemon-reload")
        except ServiceError as e:
            _err(f"hark service: {e}")
            return 1
        _out(f"disabled: {', '.join(units)}")
        return 0

    def restart(self, components: Sequence[str]) -> int:
        units = [UNITS[c] for c in components]
        try:
            self._check("restart", *units)
        except ServiceError as e:
            _err(f"hark service: {e}")
            return 1
        _out(f"restarted: {', '.join(units)}")
        return 0

    def status(self, components: Sequence[str]) -> list[Status]:
        props = "LoadState,ActiveState,SubState,UnitFileState,NRestarts,FragmentPath"
        units = [UNITS[c] for c in components]
        try:
            p = self._systemctl("show", f"--property={props}", *units)
        except ServiceError as e:
            return [Status(c, UNITS[c], installed=False, enabled=False, active=False,
                           detail=str(e)) for c in components]  # fmt: skip
        blocks = [b for b in p.stdout.split("\n\n") if b.strip()]
        if p.returncode != 0 or len(blocks) != len(units):
            detail = p.stderr.strip() or "unexpected systemctl output"
            return [Status(c, UNITS[c], installed=False, enabled=False, active=False,
                           detail=detail) for c in components]  # fmt: skip
        rows: list[Status] = []
        for c, block in zip(components, blocks, strict=True):
            kv = dict(line.split("=", 1) for line in block.splitlines() if "=" in line)
            restarts = int(kv.get("NRestarts", "0") or 0)
            installed = kv.get("LoadState") == "loaded"
            detail = ", ".join(
                x
                for x in (
                    kv.get("SubState", "") if installed else "",
                    f"{restarts} restarts" if restarts else "",
                    kv.get("FragmentPath", ""),
                )
                if x
            )
            rows.append(
                Status(
                    component=c,
                    name=UNITS[c],
                    installed=installed,
                    enabled=kv.get("UnitFileState", "").startswith("enabled"),
                    active=kv.get("ActiveState") == "active",
                    detail=detail,
                )
            )
        return rows


def backend() -> SystemdBackend:
    return SystemdBackend()


# --- sd_notify(3), used by `hark run` ---------------------------------------------------------


def notify(state: str) -> bool:
    """Send ``state`` (e.g. ``"READY=1"``) to the service manager; False if there is none."""
    import socket  # noqa: PLC0415 - only the daemon needs it

    addr = os.environ.get("NOTIFY_SOCKET", "")
    if addr.startswith("@"):  # abstract namespace
        addr = "\0" + addr[1:]
    elif not addr.startswith("/"):
        return False  # unset, or a transport we do not speak (vsock)
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_DGRAM) as s:
            s.connect(addr)
            s.sendall(state.encode())
    except OSError as e:
        log.warning("sd_notify %r failed: %s", state.split("=", 1)[0], e)
        return False
    return True


def watchdog_interval() -> float | None:
    """Seconds between ``WATCHDOG=1`` pings (half of ``WatchdogSec``), None if not enabled."""
    pid = os.environ.get("WATCHDOG_PID", "")
    if pid and pid != str(os.getpid()):
        return None
    try:
        usec = int(os.environ.get("WATCHDOG_USEC", ""))
    except ValueError:
        return None
    return usec / 2e6 if usec > 0 else None


def start_watchdog(healthy: Callable[[], bool], stop: threading.Event) -> threading.Thread | None:
    """Feed the watchdog while ``healthy()`` holds, until ``stop`` is set; None if the unit has
    no ``WatchdogSec``."""
    interval = watchdog_interval()
    if interval is None:
        return None

    def loop() -> None:
        was_ok = True
        while True:
            try:
                ok = healthy()
            except Exception:  # noqa: BLE001 - any failure means "not healthy"
                ok = False
            if ok:
                notify("WATCHDOG=1")
            elif was_ok:
                log.warning("watchdog: health check failed; not feeding systemd's watchdog")
            was_ok = ok
            if stop.wait(interval):
                return

    thread = threading.Thread(target=loop, daemon=True, name="hark-watchdog")
    thread.start()
    return thread


if __name__ == "__main__":
    # Regenerate the packaged units: python -m skriv_client.service.linux packaging/systemd
    out_dir = Path(sys.argv[1])
    for component, unit in UNITS.items():
        (out_dir / unit).write_text(render(component, PACKAGED))
